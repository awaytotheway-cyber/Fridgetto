/**
 * Generates src/lib/image-blur.ts: a tiny blurred preview of every image in
 * public/assets, inlined as a data URL. next/image shows it immediately, so a card
 * never sits as an empty box while the real picture arrives.
 *
 * Run after adding or replacing anything in public/assets:
 *   node scripts/make-image-blur.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetDir = join(root, "public/assets");
const outFile = join(root, "src/lib/image-blur.ts");

const files = (await readdir(assetDir)).filter((f) => /\.(webp|png|jpe?g)$/i.test(f)).sort();

const entries = [];
for (const file of files) {
  // 12px wide is enough to suggest the shape and colour; quality 35 keeps it a few hundred bytes
  const buf = await sharp(join(assetDir, file)).resize(12).webp({ quality: 35 }).toBuffer();
  entries.push([`/assets/${file}`, `data:image/webp;base64,${buf.toString("base64")}`]);
}

const body = entries.map(([path, data]) => `  "${path}":\n    "${data}",`).join("\n");

await writeFile(
  outFile,
  `/**
 * Generated by scripts/make-image-blur.mjs — do not edit by hand.
 * A 12px-wide preview of each file in public/assets, shown by next/image while the
 * full picture loads. Re-run the script after changing anything in that folder.
 */
export const imageBlur: Record<string, string> = {
${body}
};

/** The preview for an image path, or undefined if it has not been generated. */
export function blurFor(src: string | null | undefined) {
  return src ? imageBlur[src] : undefined;
}
`,
);

const total = entries.reduce((n, [, d]) => n + d.length, 0);
console.log(`image-blur: ${entries.length} previews, ${(total / 1024).toFixed(1)} KB inline`);
