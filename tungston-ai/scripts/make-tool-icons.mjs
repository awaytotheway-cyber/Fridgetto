/**
 * Generates src/lib/tool-icons.ts from src/lib/tools.json: the logo path and brand colour
 * of every tool that names an `icon`, taken from Simple Icons at a pinned version so the
 * output is reproducible. The result is committed, so builds need no network.
 *
 * Run after adding or changing a tool that has an icon:
 *   node scripts/make-tool-icons.mjs
 *
 * A tool without an `icon` shows its name only. That is deliberate for brands whose logo
 * is not in Simple Icons (HeyGen, Vapi, Retell, Pipedrive) or was withdrawn from it at the
 * owner's request (Microsoft); do not work around it by copying a logo from elsewhere.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "13.21.0";
const CDN = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const tools = JSON.parse(await readFile(join(root, "src/lib/tools.json"), "utf8"));
const catalogue = JSON.parse(await (await fetch(`${CDN}/_data/simple-icons.json`)).text());
const entries = Array.isArray(catalogue) ? catalogue : catalogue.icons;
const hexBySlug = new Map(
  entries.map((e) => [e.slug ?? e.title.toLowerCase().replace(/[^a-z0-9]/g, ""), e.hex]),
);

/** WCAG relative luminance, so a near-black brand colour can be swapped on a dark page. */
function luminance(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const OFF_WHITE = "f3f1ee";
const out = [];
for (const [id, tool] of Object.entries(tools)) {
  if (!tool.icon) continue;
  const res = await fetch(`${CDN}/icons/${tool.icon}.svg`);
  if (!res.ok) throw new Error(`${id}: no Simple Icons file for "${tool.icon}" (HTTP ${res.status})`);
  const path = (await res.text()).match(/ d="([^"]+)"/)?.[1];
  const hex = hexBySlug.get(tool.icon);
  if (!path || !hex) throw new Error(`${id}: could not read the path or colour for "${tool.icon}"`);
  // Brand colour on hover, unless it would vanish against the dark background
  const hover = luminance(hex) < 0.12 ? OFF_WHITE : hex;
  out.push(`  ${id}: {\n    path:\n      "${path}",\n    hover: "#${hover}",\n  },`);
}

await writeFile(
  join(root, "src/lib/tool-icons.ts"),
  `/**
 * Generated by scripts/make-tool-icons.mjs from tools.json: do not edit by hand.
 * Logo paths are Simple Icons ${VERSION} (CC0). Brand names and logos are trademarks of their
 * owners, shown only to indicate which tools we integrate with.
 */
export const toolIcons: Record<string, { path: string; hover: string }> = {
${out.join("\n")}
};
`,
);
console.log(`tool-icons: ${out.length} logos written from Simple Icons ${VERSION}`);
